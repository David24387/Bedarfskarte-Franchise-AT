const assert=require('node:assert/strict');
const D=require('../directory.js');
const base={kst:'DEMO-ONLY-1',firma:'FIKTIVER Demo-Betrieb',str:'Erfundene Straße 1',plz:'0000',ort:'Beispielort',netz:'DEMO-1',network:'EFR',lat:48,lng:14,mappable:true};
const a=D.merge(base,{id:base.kst,state:'Demo-Region',services:['PKW','LKW'],openingHours:'Demo Mo–Fr\n08–17',locationUrl:'https://example.com',phone:'+00 000',email:'standort@example.com'});
assert(D.matches(a,['PKW','LKW'],'Demo-Region'));
assert(!D.matches(a,['Agrar'],''));
assert(!D.matches(a,[],'Andere Region'));
assert.equal(D.merge(base,{id:'OTHER',services:['Agrar']}).services.length,0);
assert.equal(D.safeUrl('javascript:alert(1)'),'');
assert.equal(D.safeUrl('https://user:pass@example.com'),'');
const malicious=D.merge({...base,firma:'<img src=x onerror=alert(1)>'},{id:base.kst,openingHours:'<script>evil()</script>',services:['<b>unsafe</b>'],website:'javascript:alert(1)',email:'bad" onmouseover="evil@example.com'});
const html=D.profile(malicious)+D.listItem(malicious);
assert(!html.includes('<script>'));
assert(!html.includes('<img'));
assert(!html.includes('href="javascript:'));
assert(html.includes('&lt;b&gt;unsafe&lt;/b&gt;'));
const f=(lat,lng,network)=>({properties:{lat,lng,network}});
assert.equal(D.attach([a],[f(48,14,'EFR'),f(48,14,'PLP'),f(47,14,'EFR')]).length,1);
const b=D.merge({...base,kst:'DEMO-ONLY-2',lat:47},{id:'DEMO-ONLY-2',services:['Agrar']});
const selected=[a,b].filter(c=>D.matches(c,['LKW']));
assert.equal(D.attach(selected,[f(48,14,'EFR'),f(47,14,'EFR')]).length,1);
assert(!D.profile(D.merge(base,null)).includes('mailto:'));
assert(D.profile(a).includes('tel:+00000'));
console.log('Directory tests passed: service AND-filter, region, details/ID boundary, links, XSS, service-specific coverage.');

const enriched=D.merge(base,{id:base.kst,partnerType:'FRPL',lifecycle:'Partner Light',partnerStatus:'Aktiv',management:'Demo <b>Name</b>',companyRegister:'FN-DEMO',vatId:'AT-DEMO',contractStart:'2020-01-01',oem:'Nein'});
const enrichedHtml=D.profile(enriched);
for(const value of ['FRPL','Partner Light','Aktiv','FN-DEMO','AT-DEMO','2020-01-01','Nein','Demo &lt;b&gt;Name&lt;/b&gt;'])assert(enrichedHtml.includes(value));
assert(!enrichedHtml.includes('<b>Name</b>'));
assert(!D.profile(D.merge(base,{id:'OTHER',management:'SECRET'})).includes('SECRET'));
